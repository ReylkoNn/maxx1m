def make_styles():
    s = {}

    s['doc_title'] = ParagraphStyle(
        'doc_title',
        fontName=FONT_BOLD,
        fontSize=16,
        leading=24,
        alignment=TA_CENTER,
        textColor=COLOR_DARK,
        spaceAfter=4,
    )
    s['doc_sub'] = ParagraphStyle(
        'doc_sub',
        fontName=FONT_ITALIC,
        fontSize=12,
        leading=18,
        alignment=TA_CENTER,
        textColor=COLOR_GREY,
        spaceAfter=2,
    )
    s['question'] = ParagraphStyle(
        'question',
        fontName=FONT_BOLD,
        fontSize=13,
        leading=20,
        alignment=TA_LEFT,
        textColor=COLOR_ACCENT,
        spaceBefore=14,
        spaceAfter=6,
    )
    s['body'] = ParagraphStyle(
        'body',
        fontName=FONT_MAIN,
        fontSize=12,
        leading=20,
        alignment=TA_JUSTIFY,
        textColor=COLOR_DARK,
        firstLineIndent=12*mm,
        spaceAfter=5,
    )
    s['body_no_indent'] = ParagraphStyle(
        'body_no_indent',
        fontName=FONT_MAIN,
        fontSize=12,
        leading=20,
        alignment=TA_JUSTIFY,
        textColor=COLOR_DARK,
        spaceAfter=5,
    )
    s['bullet'] = ParagraphStyle(
        'bullet',
        fontName=FONT_MAIN,
        fontSize=12,
        leading=20,
        alignment=TA_JUSTIFY,
        textColor=COLOR_DARK,
        leftIndent=14*mm,
        firstLineIndent=0,
        spaceAfter=3,
    )
    s['italic_note'] = ParagraphStyle(
        'italic_note',
        fontName=FONT_ITALIC,
        fontSize=11,
        leading=17,
        alignment=TA_JUSTIFY,
        textColor=COLOR_GREY,
        leftIndent=8*mm,
        rightIndent=8*mm,
        spaceAfter=6,
        spaceBefore=4,
    )
    s['footer_style'] = ParagraphStyle(
        'footer_style',
        fontName=FONT_ITALIC,
        fontSize=10,
        leading=14,
        alignment=TA_CENTER,
        textColor=COLOR_GREY,
    )
    return s


def hr(color=COLOR_LINE, thickness=0.8):
    return HRFlowable(width="100%", thickness=thickness,
                      color=color, spaceAfter=4, spaceBefore=4)


def sp(h=4):
    return Spacer(1, h * mm)


# ─────────────────────────────────────────────
#  НУМЕРАЦИЯ СТРАНИЦ
# ─────────────────────────────────────────────
def on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont(FONT_MAIN, 10)
    canvas.setFillColor(COLOR_GREY)
    canvas.drawCentredString(A4[0] / 2, 12 * mm, str(doc.page))
    canvas.restoreState()


